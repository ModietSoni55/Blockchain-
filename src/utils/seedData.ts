function createSeedPack(
  serialNumber: string,
  batch: BatchRecord,
  tokenId: number,
  status: MedicinePackRecord['status'],
  currentCustodian: string,
  custodianRole: MedicinePackRecord['custodianRole'],
  scanCount = 0,
  isSuspicious = false,
  suspicionReason?: string,
  location?: { label: string; lat: number; lon: number }
): MedicinePackRecord {
  const serialHash = computeKeccakHex(serialNumber);
  const nonce = computeKeccakHex(`nonce:${serialNumber}`);
  const signature = signQRPayload(serialNumber, batch.batchId, batch.expiresAt, nonce);
  const pufSealHash = deriveDeterministicPUFPrint(serialNumber, batch.batchId);
  return {
    serialNumber,
    serialHash,
    batchId: batch.batchId,
    tokenId,
    status,
    currentCustodian,
    custodianRole,
    nonce,
    signature,
    scanCount,
    isSuspicious,
    suspicionReason,
    lastScannedLocation: location?.label || 'Boston Medical Receiving Vault, Boston, MA',
    lastScanLat: location?.lat ?? 42.3601,
    lastScanLon: location?.lon ?? -71.0589,
    lastScanTimestamp: '2026-11-12T05:30:00.000Z',
    pufSealHash,
  };
}

